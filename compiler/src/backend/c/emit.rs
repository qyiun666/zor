//! IR → C11 源（确定性输出）。
//!
//! 运行时面：`Box<i64>` 用 `malloc`／`free`，每枚 owner 槽位带运行期 drop flag；
//! 作用域结束按 IR 给定的逆序释放仍活跃的 owner；不调用 printf 家族，不依赖
//! C 字符串转义；`#line` 把 C 行号映回 `.zor`。

use std::collections::HashMap;
use std::fmt::Write as _;

use super::super::ir::{Func, LocalId, Program, Stmt, StrArg};

pub fn emit(prog: &Program, source_path: &str) -> String {
    let mut out = String::new();
    out.push_str("/* generated by zorcc C backend; do not edit */\n");
    out.push_str("#include <stddef.h>\n#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n\n");
    if prog_uses_alloc(prog) {
        emit_alloc_helper(&mut out);
    }
    for f in &prog.funcs {
        emit_func(&mut out, f, source_path);
    }
    out
}

fn prog_uses_alloc(prog: &Program) -> bool {
    prog.funcs.iter().any(|f| {
        f.body
            .iter()
            .any(|s| matches!(s, Stmt::BindBox { .. } | Stmt::BindBoxAssign { .. }))
    })
}

fn emit_alloc_helper(out: &mut String) {
    out.push_str("static void *zor_alloc(size_t n) {\n");
    out.push_str("    void *p = malloc(n);\n");
    out.push_str("    if (p == NULL) {\n");
    out.push_str("        fputs(\"zorcc: out of memory\\n\", stderr);\n");
    out.push_str("        exit(1);\n");
    out.push_str("    }\n");
    out.push_str("    return p;\n");
    out.push_str("}\n\n");
}

/// C 标识符 mangle：`zor_<kind>_<index>[_<sanitized>]`。
pub fn mangle(kind: &str, index: usize, name: &str) -> String {
    let mut s = format!("zor_{}_{}", kind, index);
    if !name.is_empty() {
        s.push('_');
        for ch in name.chars() {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                s.push(ch);
            } else {
                s.push('_');
            }
        }
    }
    s
}

/// `#line` 文件名转义：`"`／`\` 转义，控制字符与非 ASCII 字节用三位八进制。
pub fn escape_line_filename(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for &b in path.as_bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            0x20..=0x7e => out.push(b as char),
            _ => {
                out.push('\\');
                let _ = write!(out, "{:03o}", b);
            }
        }
    }
    out
}

fn emit_func(out: &mut String, f: &Func, source_path: &str) {
    let src = escape_line_filename(source_path);
    let cname = if f.name == "main" {
        "main".to_string()
    } else {
        mangle("fn", 0, &f.name)
    };
    let _ = writeln!(out, "#line {} \"{}\"", f.line.max(1), src);
    let _ = writeln!(out, "int {cname}(void) {{");

    // 预扫分配标签，保证 Println 引用的数组必然已声明。
    let mut labels: HashMap<LocalId, (String, usize)> = HashMap::new();
    let mut counter = 0usize;
    for st in &f.body {
        if let Stmt::BindStr { local, bytes, .. } = st {
            labels.insert(*local, (mangle("str", counter, ""), bytes.len()));
            counter += 1;
        }
    }

    // 每枚 Box owner 槽位：载荷指针 + 运行期 drop flag（静态 drop_dst 的运行时载体）。
    let box_locals = box_locals(f);
    for id in &box_locals {
        let _ = writeln!(out, "    int64_t *zor_box_{} = NULL;", id.0);
        let _ = writeln!(out, "    uint8_t zor_live_{} = 0;", id.0);
    }
    if !box_locals.is_empty() {
        out.push('\n');
    }

    for st in &f.body {
        match st {
            Stmt::BindStr { local, bytes, line, .. } => {
                if let Some((label, _)) = labels.get(local) {
                    let _ = writeln!(out, "#line {} \"{}\"", line, src);
                    emit_array(out, label, bytes);
                }
            }
            Stmt::Println { arg, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                match arg {
                    StrArg::Local(id) => {
                        if let Some((label, len)) = labels.get(id) {
                            let _ = writeln!(out, "    fwrite({label}, 1, {len}, stdout);");
                            let _ = writeln!(out, "    fputc('\\n', stdout);");
                        }
                    }
                    StrArg::Bytes(bytes) => {
                        let label = mangle("str", counter, "");
                        counter += 1;
                        emit_array(out, &label, bytes);
                        let _ = writeln!(
                            out,
                            "    fwrite({label}, 1, {}, stdout);",
                            bytes.len()
                        );
                        let _ = writeln!(out, "    fputc('\\n', stdout);");
                    }
                }
            }
            Stmt::BindI64 { local, value, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                let _ = writeln!(out, "    int64_t zor_i64_{} = {};", local.0, c_i64(*value));
            }
            Stmt::BindBox { local, value, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                emit_alloc_box(out, local, *value);
            }
            Stmt::BindBoxAssign { local, value, drop_dst, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                if *drop_dst {
                    emit_free_live(out, local);
                }
                emit_alloc_box(out, local, *value);
            }
            Stmt::BindI64Deref { local, src: boxed, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                let _ = writeln!(
                    out,
                    "    int64_t zor_i64_{} = *zor_box_{};",
                    local.0, boxed.0
                );
            }
            Stmt::MoveAssign { dst, src: from, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                emit_move(out, dst, from);
            }
            Stmt::OverwriteAssign { dst, src: from, drop_dst, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                if *drop_dst {
                    emit_free_live(out, dst);
                }
                emit_move(out, dst, from);
            }
            Stmt::SelfAssign { line, .. } => {
                // 自赋值不产生释放，也不改变 owner 槽位状态。
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                out.push_str("    (void)0;\n");
            }
            Stmt::Unbox { local, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                emit_free_live(out, local);
            }
            Stmt::ScopeExit { drops, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                for id in drops {
                    emit_free_live(out, id);
                }
            }
        }
    }
    out.push_str("    return 0;\n}\n");
}

/// 按 lower 给定的逆序／单点顺序释放：运行期 flag 保证每枚载荷至多 free 一次。
fn emit_free_live(out: &mut String, id: &LocalId) {
    let _ = writeln!(out, "    if (zor_live_{}) {{", id.0);
    let _ = writeln!(out, "        free(zor_box_{});", id.0);
    let _ = writeln!(out, "        zor_live_{} = 0;", id.0);
    let _ = writeln!(out, "    }}");
}

fn emit_alloc_box(out: &mut String, id: &LocalId, value: i64) {
    let _ = writeln!(
        out,
        "    zor_box_{} = (int64_t *)zor_alloc(sizeof(int64_t));",
        id.0
    );
    let _ = writeln!(out, "    *zor_box_{} = {};", id.0, c_i64(value));
    let _ = writeln!(out, "    zor_live_{} = 1;", id.0);
}

/// 移动：所有权转给目标，源槽位置为无活值；不释放载荷。
fn emit_move(out: &mut String, dst: &LocalId, src: &LocalId) {
    let _ = writeln!(out, "    zor_box_{} = zor_box_{};", dst.0, src.0);
    let _ = writeln!(out, "    zor_live_{} = 1;", dst.0);
    let _ = writeln!(out, "    zor_live_{} = 0;", src.0);
}

/// i64 字面量的 C11 安全写法（`INT64_MIN` 不写成不可表示的正字面量）。
fn c_i64(v: i64) -> String {
    if v == i64::MIN {
        "(-INT64_C(9223372036854775807) - 1)".to_string()
    } else if v < 0 {
        format!("(-INT64_C({}))", -v)
    } else {
        format!("INT64_C({v})")
    }
}

fn box_locals(f: &Func) -> Vec<LocalId> {
    fn add(ids: &mut Vec<LocalId>, id: LocalId) {
        if !ids.contains(&id) {
            ids.push(id);
        }
    }
    let mut ids = Vec::new();
    for st in &f.body {
        match st {
            Stmt::BindBox { local, .. }
            | Stmt::BindBoxAssign { local, .. }
            | Stmt::Unbox { local, .. } => add(&mut ids, *local),
            Stmt::BindI64Deref { src, .. } => add(&mut ids, *src),
            Stmt::MoveAssign { dst, src, .. } | Stmt::OverwriteAssign { dst, src, .. } => {
                add(&mut ids, *dst);
                add(&mut ids, *src);
            }
            Stmt::ScopeExit { drops, .. } => {
                for id in drops {
                    add(&mut ids, *id);
                }
            }
            Stmt::BindStr { .. }
            | Stmt::Println { .. }
            | Stmt::BindI64 { .. }
            | Stmt::SelfAssign { .. } => {}
        }
    }
    ids
}

fn emit_array(out: &mut String, label: &str, bytes: &[u8]) {
    let n = bytes.len();
    if n == 0 {
        // C11 无零长数组；空串用 1 字节占位，长度仍为 0。
        let _ = writeln!(out, "    static const uint8_t {label}[1] = {{0}};");
        return;
    }
    let hex: Vec<String> = bytes.iter().map(|b| format!("0x{:02x}", b)).collect();
    if hex.len() <= 16 {
        let _ = writeln!(
            out,
            "    static const uint8_t {label}[{n}] = {{{}}};",
            hex.join(", ")
        );
    } else {
        let _ = writeln!(out, "    static const uint8_t {label}[{n}] = {{");
        for chunk in hex.chunks(12) {
            let _ = writeln!(out, "        {},", chunk.join(", "));
        }
        let _ = writeln!(out, "    }};");
    }
}

#[cfg(test)]
mod tests {
    use super::{c_i64, emit, escape_line_filename, mangle};
    use crate::backend::lower;
    use crate::compile_typed;

    fn ir(src: &str) -> crate::backend::ir::Program {
        let c = compile_typed(src);
        assert!(c.diags.is_empty(), "{:?}", c.diags);
        lower::lower(&c.prog, &c.types).expect("lower")
    }

    #[test]
    fn hello_emits_byte_array_and_fwrite() {
        let p = ir("fn main() {\n    let greeting = \"Hello, ZOR\";\n    println(greeting);\n}\n");
        let c = emit(&p, "examples/hello.zor");
        assert!(c.contains("#line 1 \"examples/hello.zor\""), "{c}");
        assert!(c.contains("#line 2 \"examples/hello.zor\""), "{c}");
        assert!(c.contains("#line 3 \"examples/hello.zor\""), "{c}");
        assert!(c.contains("static const uint8_t zor_str_0[10] = {0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x2c, 0x20, 0x5a, 0x4f, 0x52};"), "{c}");
        assert!(c.contains("fwrite(zor_str_0, 1, 10, stdout);"), "{c}");
        assert!(c.contains("fputc('\\n', stdout);"), "{c}");
        assert!(c.contains("int main(void) {"), "{c}");
        assert!(c.contains("return 0;"), "{c}");
    }

    #[test]
    fn empty_string_uses_one_byte_placeholder() {
        let p = ir("fn main() { let s = \"\"; println(s); }");
        let c = emit(&p, "t.zor");
        assert!(c.contains("static const uint8_t zor_str_0[1] = {0};"), "{c}");
        assert!(c.contains("fwrite(zor_str_0, 1, 0, stdout);"), "{c}");
    }

    #[test]
    fn utf8_bytes_are_emitted_verbatim() {
        let p = ir("fn main() { let s = \"你好\"; println(s); }");
        let c = emit(&p, "t.zor");
        assert!(
            c.contains("zor_str_0[6] = {0xe4, 0xbd, 0xa0, 0xe5, 0xa5, 0xbd}"),
            "{c}"
        );
        assert!(c.contains("fwrite(zor_str_0, 1, 6, stdout);"), "{c}");
    }

    #[test]
    fn literal_println_emits_inline_array() {
        let p = ir("fn main() { println(\"hi\"); }");
        let c = emit(&p, "t.zor");
        assert!(c.contains("zor_str_0[2] = {0x68, 0x69}"), "{c}");
        assert!(c.contains("fwrite(zor_str_0, 1, 2, stdout);"), "{c}");
    }

    #[test]
    fn line_filename_is_escaped() {
        assert_eq!(escape_line_filename("a\"b\\c\nd"), "a\\\"b\\\\c\\012d");
        assert_eq!(
            escape_line_filename("你好"),
            "\\344\\275\\240\\345\\245\\275"
        );
    }

    #[test]
    fn mangle_sanitizes_identifiers() {
        assert_eq!(mangle("str", 0, ""), "zor_str_0");
        assert_eq!(mangle("fn", 3, "main"), "zor_fn_3_main");
        assert_eq!(mangle("fn", 1, "a-b c"), "zor_fn_1_a_b_c");
    }

    #[test]
    fn output_is_deterministic() {
        let p = ir("fn main() { let s = \"x\"; println(s); }");
        assert_eq!(emit(&p, "t.zor"), emit(&p, "t.zor"));
    }

    // —— CORE-04 运行期：malloc／free／drop flag ——

    #[test]
    fn box_create_read_unbox_emits_alloc_load_and_one_free() {
        let p = ir("fn main() {\n    let b = box 1;\n    let v = *b;\n    unbox b;\n}\n");
        let c = emit(&p, "t.zor");
        assert!(c.contains("zor_box_0 = (int64_t *)zor_alloc(sizeof(int64_t));"), "{c}");
        assert!(c.contains("*zor_box_0 = INT64_C(1);"), "{c}");
        assert!(c.contains("zor_live_0 = 1;"), "{c}");
        assert!(c.contains("int64_t zor_i64_1 = *zor_box_0;"), "{c}");
        assert!(c.contains("if (zor_live_0) {"), "{c}");
        assert_eq!(c.matches("free(zor_box_0);").count(), 1, "{c}");
        assert_eq!(c.matches("free(").count(), 1, "{c}");
    }

    #[test]
    fn scope_exit_frees_in_reverse_declaration_order() {
        let p = ir("fn main() {\n    let a = box 1;\n    let b = box 2;\n}\n");
        let c = emit(&p, "t.zor");
        let first = c.find("free(zor_box_1);").expect("free b");
        let second = c.find("free(zor_box_0);").expect("free a");
        assert!(first < second, "逆序 drop 被破坏：{c}");
    }

    #[test]
    fn overwrite_frees_old_before_taking_moved_pointer() {
        let p = ir("fn main() {\n    let a = box 1;\n    let b = box 2;\n    a = b;\n}\n");
        let c = emit(&p, "t.zor");
        let free_old = c.find("free(zor_box_0);").expect("drop old a");
        let take = c.find("zor_box_0 = zor_box_1;").expect("move b into a");
        assert!(free_old < take, "覆盖必须先 drop 旧值：{c}");
        assert!(c.contains("zor_live_1 = 0;"), "{c}");
        assert_eq!(c.matches("free(zor_box_0);").count(), 2, "{c}");
        assert_eq!(c.matches("free(zor_box_1);").count(), 0, "{c}");
    }

    #[test]
    fn move_transfers_ownership_without_extra_free() {
        let p = ir("fn main() {\n    let a = box 1;\n    let b = a;\n}\n");
        let c = emit(&p, "t.zor");
        assert!(c.contains("zor_box_1 = zor_box_0;"), "{c}");
        assert!(c.contains("zor_live_1 = 1;"), "{c}");
        assert!(c.contains("zor_live_0 = 0;"), "{c}");
        assert_eq!(c.matches("free(zor_box_0);").count(), 0, "{c}");
        assert_eq!(c.matches("free(zor_box_1);").count(), 1, "{c}");
    }

    #[test]
    fn self_assign_emits_no_free_and_keeps_owner_live() {
        let p = ir("fn main() {\n    let a = box 1;\n    a = a;\n}\n");
        let c = emit(&p, "t.zor");
        assert!(c.contains("(void)0;"), "{c}");
        assert_eq!(c.matches("free(").count(), 1, "{c}");
        assert_eq!(c.matches("free(zor_box_0);").count(), 1, "{c}");
        assert!(!c.contains("zor_box_0 = zor_box_0;"), "{c}");
    }

    #[test]
    fn unbox_then_reinit_allocs_twice_and_frees_twice() {
        let p = ir("fn main() {\n    let a = box 1;\n    unbox a;\n    a = box 2;\n}\n");
        let c = emit(&p, "t.zor");
        assert_eq!(
            c.matches("zor_box_0 = (int64_t *)zor_alloc(sizeof(int64_t));").count(),
            2,
            "{c}"
        );
        assert_eq!(c.matches("free(zor_box_0);").count(), 2, "{c}");
        assert!(c.contains("*zor_box_0 = INT64_C(2);"), "{c}");
    }

    #[test]
    fn i64_literals_are_c11_safe() {
        assert_eq!(c_i64(0), "INT64_C(0)");
        assert_eq!(c_i64(7), "INT64_C(7)");
        assert_eq!(c_i64(-5), "(-INT64_C(5))");
        assert_eq!(
            c_i64(i64::MIN),
            "(-INT64_C(9223372036854775807) - 1)"
        );
    }
}
