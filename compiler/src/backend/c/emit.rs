//! IR → C11 源（确定性输出）。
//!
//! 运行时面：`Box<i64>` 用 `malloc`／`free`，每枚 owner 槽位带运行期 drop flag；
//! 作用域结束按 IR 给定的逆序释放仍活跃的 owner；不调用 printf 家族，不依赖
//! C 字符串转义；`#line` 把 C 行号映回 `.zor`。

use std::collections::HashMap;
use std::fmt::Write as _;

use super::super::ir::{
    ArithOp, Func, IntExpr, IntTy, LocalId, PrintArg, Program, Stmt, StrArg, Value,
};
use crate::backend::OverflowMode;

/// `println` 的原子写出单元：编译期字节片段或运行期整型表达式。
enum Part {
    Bytes(String, usize),
    Int(IntTy, String),
}

pub fn emit(prog: &Program, source_path: &str, overflow: OverflowMode) -> String {
    let mut out = String::new();
    out.push_str("/* generated by zorcc C backend; do not edit */\n");
    out.push_str("#include <stddef.h>\n#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n");
    if prog_uses_int_arith(prog) {
        out.push_str("#include <string.h>\n#include \"zor_rt.h\"\n");
    }
    out.push('\n');
    if prog_uses_alloc(prog) {
        emit_alloc_helper(&mut out);
    }
    for f in &prog.funcs {
        emit_func(&mut out, f, source_path, overflow);
    }
    out
}

fn prog_uses_int_arith(prog: &Program) -> bool {
    prog.funcs.iter().any(|f| {
        f.body.iter().any(|s| match s {
            Stmt::BindInt { .. } | Stmt::EvalInt { .. } => true,
            Stmt::Print { args, .. } => args.iter().any(|a| match a {
                PrintArg::Int { expr, .. } => {
                    !matches!(expr, IntExpr::Const(_) | IntExpr::Local(_))
                }
                PrintArg::Composite(v) => value_needs_arith_helpers(v),
                _ => false,
            }),
            _ => false,
        })
    })
}

fn prog_uses_alloc(prog: &Program) -> bool {
    prog.funcs.iter().any(|f| {
        f.body
            .iter()
            .any(|s| matches!(s, Stmt::BindBox { .. } | Stmt::BindBoxAssign { .. }))
    })
}

fn emit_alloc_helper(out: &mut String) {
    out.push_str("static void *zor_alloc(size_t n) {\n");
    out.push_str("    void *p = malloc(n);\n");
    out.push_str("    if (p == NULL) {\n");
    out.push_str("        fputs(\"zorcc: out of memory\\n\", stderr);\n");
    out.push_str("        exit(1);\n");
    out.push_str("    }\n");
    out.push_str("    return p;\n");
    out.push_str("}\n\n");
}

/// C 标识符 mangle：`zor_<kind>_<index>[_<sanitized>]`。
pub fn mangle(kind: &str, index: usize, name: &str) -> String {
    let mut s = format!("zor_{}_{}", kind, index);
    if !name.is_empty() {
        s.push('_');
        for ch in name.chars() {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                s.push(ch);
            } else {
                s.push('_');
            }
        }
    }
    s
}

/// `#line` 文件名转义：`"`／`\` 转义，控制字符与非 ASCII 字节用三位八进制。
pub fn escape_line_filename(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for &b in path.as_bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            0x20..=0x7e => out.push(b as char),
            _ => {
                out.push('\\');
                let _ = write!(out, "{:03o}", b);
            }
        }
    }
    out
}

/// 复合值的编译期结构：按契约模板递归展开为字节片段与运行期整型单元。
/// 空字节片段（空 `[byte; N]`／空字符串）不产生写调用，但位置与分隔符不变。
fn flatten_value(
    v: &Value,
    parts: &mut Vec<Part>,
    out: &mut String,
    counter: &mut usize,
    overflow: OverflowMode,
    tmp_counter: &mut usize,
) {
    match v {
        Value::Int { ty, expr } => {
            let val = emit_int_expr(out, expr, *ty, overflow, tmp_counter);
            parts.push(Part::Int(*ty, val));
        }
        Value::Bytes(bytes) => push_bytes_part(parts, out, counter, bytes),
        Value::Tuple(vs) => {
            if vs.is_empty() {
                push_bytes_part(parts, out, counter, b"()");
                return;
            }
            push_bytes_part(parts, out, counter, b"(");
            for (i, x) in vs.iter().enumerate() {
                if i > 0 {
                    push_bytes_part(parts, out, counter, b", ");
                }
                flatten_value(x, parts, out, counter, overflow, tmp_counter);
            }
            push_bytes_part(parts, out, counter, b")");
        }
        Value::Array(vs) => {
            push_bytes_part(parts, out, counter, b"[");
            for (i, x) in vs.iter().enumerate() {
                if i > 0 {
                    push_bytes_part(parts, out, counter, b", ");
                }
                flatten_value(x, parts, out, counter, overflow, tmp_counter);
            }
            push_bytes_part(parts, out, counter, b"]");
        }
        Value::Struct { name, fields } => {
            if fields.is_empty() {
                push_bytes_part(parts, out, counter, format!("{} {{}}", name).as_bytes());
                return;
            }
            push_bytes_part(parts, out, counter, format!("{} {{ ", name).as_bytes());
            for (i, (fname, fv)) in fields.iter().enumerate() {
                if i > 0 {
                    push_bytes_part(parts, out, counter, b", ");
                }
                push_bytes_part(parts, out, counter, format!("{}: ", fname).as_bytes());
                flatten_value(fv, parts, out, counter, overflow, tmp_counter);
            }
            push_bytes_part(parts, out, counter, b" }");
        }
        Value::Enum { variant, payload } => {
            if payload.is_empty() {
                push_bytes_part(parts, out, counter, variant.as_bytes());
                return;
            }
            push_bytes_part(parts, out, counter, format!("{}(", variant).as_bytes());
            for (i, x) in payload.iter().enumerate() {
                if i > 0 {
                    push_bytes_part(parts, out, counter, b", ");
                }
                flatten_value(x, parts, out, counter, overflow, tmp_counter);
            }
            push_bytes_part(parts, out, counter, b")");
        }
    }
}

fn push_bytes_part(parts: &mut Vec<Part>, out: &mut String, counter: &mut usize, bytes: &[u8]) {
    if bytes.is_empty() {
        return;
    }
    let label = mangle("str", *counter, "");
    *counter += 1;
    emit_array(out, &label, bytes);
    parts.push(Part::Bytes(label, bytes.len()));
}

fn value_needs_arith_helpers(v: &Value) -> bool {
    match v {
        Value::Int { expr, .. } => {
            !matches!(expr, IntExpr::Const(_) | IntExpr::Local(_))
        }
        Value::Tuple(vs) | Value::Array(vs) => vs.iter().any(value_needs_arith_helpers),
        Value::Struct { fields, .. } => {
            fields.iter().any(|(_, x)| value_needs_arith_helpers(x))
        }
        Value::Enum { payload, .. } => payload.iter().any(value_needs_arith_helpers),
        Value::Bytes(_) => false,
    }
}

fn emit_func(out: &mut String, f: &Func, source_path: &str, overflow: OverflowMode) {
    let src = escape_line_filename(source_path);
    let cname = if f.name == "main" {
        "main".to_string()
    } else {
        mangle("fn", 0, &f.name)
    };
    let _ = writeln!(out, "#line {} \"{}\"", f.line.max(1), src);
    let _ = writeln!(out, "int {cname}(void) {{");

    // 预扫分配标签，保证 Print 引用的数组必然已声明。
    let mut labels: HashMap<LocalId, (String, usize)> = HashMap::new();
    let mut counter = 0usize;
    for st in &f.body {
        if let Stmt::BindStr { local, bytes, .. } = st {
            labels.insert(*local, (mangle("str", counter, ""), bytes.len()));
            counter += 1;
        }
    }
    let mut tmp_counter = 0usize;

    // 每枚 Box owner 槽位：载荷指针 + 运行期 drop flag（静态 drop_dst 的运行时载体）。
    let box_locals = box_locals(f);
    for id in &box_locals {
        let _ = writeln!(out, "    int64_t *zor_box_{} = NULL;", id.0);
        let _ = writeln!(out, "    uint8_t zor_live_{} = 0;", id.0);
    }
    if !box_locals.is_empty() {
        out.push('\n');
    }

    for st in &f.body {
        match st {
            Stmt::BindStr { local, bytes, line, .. } => {
                if let Some((label, _)) = labels.get(local) {
                    let _ = writeln!(out, "#line {} \"{}\"", line, src);
                    emit_array(out, label, bytes);
                }
            }
            Stmt::Print { args, newline, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                // 原子性：先求值全部运行期实参（E30xx 在此终止，stdout 零字节），再统一写出。
                let mut arg_parts: Vec<Vec<Part>> = Vec::with_capacity(args.len());
                for arg in args {
                    let mut parts: Vec<Part> = Vec::new();
                    match arg {
                        PrintArg::Int { ty, expr } => {
                            let v = emit_int_expr(out, expr, *ty, overflow, &mut tmp_counter);
                            parts.push(Part::Int(*ty, v));
                        }
                        PrintArg::Str(StrArg::Local(id)) => {
                            let (label, len) = labels
                                .get(id)
                                .unwrap_or_else(|| panic!("missing string label for local {}", id.0));
                            parts.push(Part::Bytes(label.clone(), *len));
                        }
                        PrintArg::Str(StrArg::Bytes(bytes)) | PrintArg::Bytes(bytes) => {
                            let label = mangle("str", counter, "");
                            counter += 1;
                            emit_array(out, &label, bytes);
                            parts.push(Part::Bytes(label, bytes.len()));
                        }
                        PrintArg::Composite(value) => {
                            flatten_value(
                                value,
                                &mut parts,
                                out,
                                &mut counter,
                                overflow,
                                &mut tmp_counter,
                            );
                        }
                    }
                    arg_parts.push(parts);
                }
                for (i, parts) in arg_parts.iter().enumerate() {
                    if i > 0 {
                        out.push_str("    fputc(' ', stdout);\n");
                    }
                    for part in parts {
                        match part {
                            Part::Bytes(label, len) => {
                                let _ = writeln!(out, "    fwrite({label}, 1, {len}, stdout);");
                            }
                            Part::Int(IntTy::I64, v) => {
                                let _ = writeln!(out, "    printf(\"%lld\", (long long)({}));", v);
                            }
                            Part::Int(IntTy::U8, v) | Part::Int(IntTy::U32, v) => {
                                let _ = writeln!(out, "    printf(\"%u\", (unsigned)({}));", v);
                            }
                        }
                    }
                }
                if *newline {
                    out.push_str("    fputc('\\n', stdout);\n");
                }
            }
            Stmt::BindI64 { local, value, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                let _ = writeln!(out, "    int64_t zor_i64_{} = {};", local.0, c_i64(*value));
            }
            Stmt::BindInt { local, ty, expr, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                let v = emit_int_expr(out, expr, *ty, overflow, &mut tmp_counter);
                let _ = writeln!(out, "    {} {} = {};", ty.c_ty(), int_local(*ty, local), v);
            }
            Stmt::EvalInt { ty, expr, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                let v = emit_int_expr(out, expr, *ty, overflow, &mut tmp_counter);
                let _ = writeln!(out, "    (void){};", v);
            }
            Stmt::BindBox { local, value, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                emit_alloc_box(out, local, *value);
            }
            Stmt::BindBoxAssign { local, value, drop_dst, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                if *drop_dst {
                    emit_free_live(out, local);
                }
                emit_alloc_box(out, local, *value);
            }
            Stmt::BindI64Deref { local, src: boxed, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                let _ = writeln!(
                    out,
                    "    int64_t zor_i64_{} = *zor_box_{};",
                    local.0, boxed.0
                );
            }
            Stmt::MoveAssign { dst, src: from, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                emit_move(out, dst, from);
            }
            Stmt::OverwriteAssign { dst, src: from, drop_dst, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                if *drop_dst {
                    emit_free_live(out, dst);
                }
                emit_move(out, dst, from);
            }
            Stmt::SelfAssign { line, .. } => {
                // 自赋值不产生释放，也不改变 owner 槽位状态。
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                out.push_str("    (void)0;\n");
            }
            Stmt::Unbox { local, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                emit_free_live(out, local);
            }
            Stmt::ScopeExit { drops, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                for id in drops {
                    emit_free_live(out, id);
                }
            }
        }
    }
    out.push_str("    return 0;\n}\n");
}

/// 整型局部变量名；与既有 `zor_i64_<id>` 命名保持一致。
fn int_local(ty: IntTy, id: &LocalId) -> String {
    match ty {
        IntTy::I64 => format!("zor_i64_{}", id.0),
        IntTy::U8 => format!("zor_u8_{}", id.0),
        IntTy::U32 => format!("zor_u32_{}", id.0),
    }
}

fn new_tmp(counter: &mut usize) -> String {
    let name = format!("zor_tmp_{}", *counter);
    *counter += 1;
    name
}

fn c_int_const(v: i128, ty: IntTy) -> String {
    match ty {
        IntTy::I64 => c_i64(v as i64),
        IntTy::U8 => format!("UINT8_C({v})"),
        IntTy::U32 => format!("UINT32_C({v})"),
    }
}

/// 递归生成算术表达式：每个节点落到独立临时变量，保证检查顺序与源序一致。
/// E30xx 仅以数值 3001／3002 传给 helper；本文件不出现运行期码位字面。
fn emit_int_expr(
    out: &mut String,
    e: &IntExpr,
    ty: IntTy,
    mode: OverflowMode,
    counter: &mut usize,
) -> String {
    match e {
        IntExpr::Const(v) => {
            let t = new_tmp(counter);
            let _ = writeln!(out, "    {} {} = {};", ty.c_ty(), t, c_int_const(*v, ty));
            t
        }
        IntExpr::Local(id) => int_local(ty, id),
        IntExpr::Neg { expr, line, col } => {
            let a = emit_int_expr(out, expr, ty, mode, counter);
            match mode {
                OverflowMode::Check => emit_checked_bin(out, ty, ArithOp::Sub, "INT64_C(0)", &a, *line, *col, counter),
                OverflowMode::Wrap => emit_wrap_bin(out, ty, ArithOp::Sub, "0", &a, counter),
            }
        }
        IntExpr::Bin { op, lhs, rhs, line, col } => {
            let a = emit_int_expr(out, lhs, ty, mode, counter);
            let b = emit_int_expr(out, rhs, ty, mode, counter);
            match op {
                ArithOp::Add | ArithOp::Sub | ArithOp::Mul => match mode {
                    OverflowMode::Check => {
                        emit_checked_bin(out, ty, *op, &a, &b, *line, *col, counter)
                    }
                    OverflowMode::Wrap => emit_wrap_bin(out, ty, *op, &a, &b, counter),
                },
                ArithOp::Div | ArithOp::Rem => {
                    emit_div_rem(out, ty, *op, &a, &b, *line, *col, mode, counter)
                }
            }
        }
    }
}

fn emit_checked_bin(
    out: &mut String,
    ty: IntTy,
    op: ArithOp,
    a: &str,
    b: &str,
    line: usize,
    col: usize,
    counter: &mut usize,
) -> String {
    let builtin = op.checked_builtin().expect("add/sub/mul");
    let t = new_tmp(counter);
    let _ = writeln!(out, "    {} {};", ty.c_ty(), t);
    let _ = writeln!(out, "    if ({builtin}(({}), ({}), &{})) {{", a, b, t);
    let _ = writeln!(out, "        zor_rt_fail(3001, __FILE__, {}, {});", line, col);
    let _ = writeln!(out, "    }}");
    t
}

fn emit_wrap_bin(
    out: &mut String,
    ty: IntTy,
    op: ArithOp,
    a: &str,
    b: &str,
    counter: &mut usize,
) -> String {
    let t = new_tmp(counter);
    let symbol = op.symbol();
    match ty {
        IntTy::I64 => {
            let _ = writeln!(out, "    int64_t {};", t);
            let _ = writeln!(out, "    {{");
            let _ = writeln!(out, "        uint64_t ua = (uint64_t)({});", a);
            let _ = writeln!(out, "        uint64_t ub = (uint64_t)({});", b);
            let _ = writeln!(out, "        uint64_t ur = ua {symbol} ub;");
            let _ = writeln!(out, "        memcpy(&{}, &ur, sizeof {});", t, t);
            let _ = writeln!(out, "    }}");
        }
        IntTy::U8 => {
            let _ = writeln!(
                out,
                "    uint8_t {} = (uint8_t)(((uint32_t)({}) {symbol} (uint32_t)({})) & 0xffu);",
                t, a, b
            );
        }
        IntTy::U32 => {
            let _ = writeln!(
                out,
                "    uint32_t {} = (uint32_t)(((uint64_t)({}) {symbol} (uint64_t)({})) & 0xffffffffu);",
                t, a, b
            );
        }
    }
    t
}

fn emit_div_rem(
    out: &mut String,
    ty: IntTy,
    op: ArithOp,
    a: &str,
    b: &str,
    line: usize,
    col: usize,
    mode: OverflowMode,
    counter: &mut usize,
) -> String {
    let helper = match (ty, op, mode) {
        (IntTy::I64, ArithOp::Div, OverflowMode::Check) => "zor_rt_div_i64_checked",
        (IntTy::I64, ArithOp::Div, OverflowMode::Wrap) => "zor_rt_div_i64_wrap",
        (IntTy::I64, ArithOp::Rem, _) => "zor_rt_rem_i64",
        (IntTy::U8, ArithOp::Div, _) => "zor_rt_div_u8",
        (IntTy::U8, ArithOp::Rem, _) => "zor_rt_rem_u8",
        (IntTy::U32, ArithOp::Div, _) => "zor_rt_div_u32",
        (IntTy::U32, ArithOp::Rem, _) => "zor_rt_rem_u32",
        _ => unreachable!("div/rem only"),
    };
    let t = new_tmp(counter);
    let _ = writeln!(
        out,
        "    {} {} = {}(({}), ({}), __FILE__, {}, {});",
        ty.c_ty(),
        t,
        helper,
        a,
        b,
        line,
        col
    );
    t
}

/// 按 lower 给定的逆序／单点顺序释放：运行期 flag 保证每枚载荷至多 free 一次。
fn emit_free_live(out: &mut String, id: &LocalId) {
    let _ = writeln!(out, "    if (zor_live_{}) {{", id.0);
    let _ = writeln!(out, "        free(zor_box_{});", id.0);
    let _ = writeln!(out, "        zor_live_{} = 0;", id.0);
    let _ = writeln!(out, "    }}");
}

fn emit_alloc_box(out: &mut String, id: &LocalId, value: i64) {
    let _ = writeln!(
        out,
        "    zor_box_{} = (int64_t *)zor_alloc(sizeof(int64_t));",
        id.0
    );
    let _ = writeln!(out, "    *zor_box_{} = {};", id.0, c_i64(value));
    let _ = writeln!(out, "    zor_live_{} = 1;", id.0);
}

/// 移动：所有权转给目标，源槽位置为无活值；不释放载荷。
fn emit_move(out: &mut String, dst: &LocalId, src: &LocalId) {
    let _ = writeln!(out, "    zor_box_{} = zor_box_{};", dst.0, src.0);
    let _ = writeln!(out, "    zor_live_{} = 1;", dst.0);
    let _ = writeln!(out, "    zor_live_{} = 0;", src.0);
}

/// i64 字面量的 C11 安全写法（`INT64_MIN` 不写成不可表示的正字面量）。
fn c_i64(v: i64) -> String {
    if v == i64::MIN {
        "(-INT64_C(9223372036854775807) - 1)".to_string()
    } else if v < 0 {
        format!("(-INT64_C({}))", -v)
    } else {
        format!("INT64_C({v})")
    }
}

fn box_locals(f: &Func) -> Vec<LocalId> {
    fn add(ids: &mut Vec<LocalId>, id: LocalId) {
        if !ids.contains(&id) {
            ids.push(id);
        }
    }
    let mut ids = Vec::new();
    for st in &f.body {
        match st {
            Stmt::BindBox { local, .. }
            | Stmt::BindBoxAssign { local, .. }
            | Stmt::Unbox { local, .. } => add(&mut ids, *local),
            Stmt::BindI64Deref { src, .. } => add(&mut ids, *src),
            Stmt::MoveAssign { dst, src, .. } | Stmt::OverwriteAssign { dst, src, .. } => {
                add(&mut ids, *dst);
                add(&mut ids, *src);
            }
            Stmt::ScopeExit { drops, .. } => {
                for id in drops {
                    add(&mut ids, *id);
                }
            }
            Stmt::BindStr { .. }
            | Stmt::Print { .. }
            | Stmt::BindI64 { .. }
            | Stmt::BindInt { .. }
            | Stmt::EvalInt { .. }
            | Stmt::SelfAssign { .. } => {}
        }
    }
    ids
}

fn emit_array(out: &mut String, label: &str, bytes: &[u8]) {
    let n = bytes.len();
    if n == 0 {
        // C11 无零长数组；空串用 1 字节占位，长度仍为 0。
        let _ = writeln!(out, "    static const uint8_t {label}[1] = {{0}};");
        return;
    }
    let hex: Vec<String> = bytes.iter().map(|b| format!("0x{:02x}", b)).collect();
    if hex.len() <= 16 {
        let _ = writeln!(
            out,
            "    static const uint8_t {label}[{n}] = {{{}}};",
            hex.join(", ")
        );
    } else {
        let _ = writeln!(out, "    static const uint8_t {label}[{n}] = {{");
        for chunk in hex.chunks(12) {
            let _ = writeln!(out, "        {},", chunk.join(", "));
        }
        let _ = writeln!(out, "    }};");
    }
}

#[cfg(test)]
