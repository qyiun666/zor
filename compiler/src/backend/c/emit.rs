//! IR → C11 源（确定性输出）。
//!
//! 首片只生成 `main`、静态字节数组与 `fwrite`／`fputc`；不调用 printf 家族，
//! 不依赖 C 字符串转义；`#line` 把 C 行号映回 `.zor`。

use std::collections::HashMap;
use std::fmt::Write as _;

use super::super::ir::{Func, LocalId, Program, Stmt, StrArg};

pub fn emit(prog: &Program, source_path: &str) -> String {
    let mut out = String::new();
    out.push_str("/* generated by zorcc 0.2.0 C backend; do not edit */\n");
    out.push_str("#include <stdint.h>\n#include <stdio.h>\n\n");
    for f in &prog.funcs {
        emit_func(&mut out, f, source_path);
    }
    out
}

/// C 标识符 mangle：`zor_<kind>_<index>[_<sanitized>]`。
pub fn mangle(kind: &str, index: usize, name: &str) -> String {
    let mut s = format!("zor_{}_{}", kind, index);
    if !name.is_empty() {
        s.push('_');
        for ch in name.chars() {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                s.push(ch);
            } else {
                s.push('_');
            }
        }
    }
    s
}

/// `#line` 文件名转义：`"`／`\` 转义，控制字符与非 ASCII 字节用三位八进制。
pub fn escape_line_filename(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for &b in path.as_bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            0x20..=0x7e => out.push(b as char),
            _ => {
                out.push('\\');
                let _ = write!(out, "{:03o}", b);
            }
        }
    }
    out
}

fn emit_func(out: &mut String, f: &Func, source_path: &str) {
    let src = escape_line_filename(source_path);
    let cname = if f.name == "main" {
        "main".to_string()
    } else {
        mangle("fn", 0, &f.name)
    };
    let _ = writeln!(out, "#line {} \"{}\"", f.line.max(1), src);
    let _ = writeln!(out, "int {cname}(void) {{");

    // 预扫分配标签，保证 Println 引用的数组必然已声明。
    let mut labels: HashMap<LocalId, (String, usize)> = HashMap::new();
    let mut counter = 0usize;
    for st in &f.body {
        if let Stmt::BindStr { local, bytes, .. } = st {
            labels.insert(*local, (mangle("str", counter, ""), bytes.len()));
            counter += 1;
        }
    }

    for st in &f.body {
        match st {
            Stmt::BindStr { local, bytes, line, .. } => {
                if let Some((label, _)) = labels.get(local) {
                    let _ = writeln!(out, "#line {} \"{}\"", line, src);
                    emit_array(out, label, bytes);
                }
            }
            Stmt::Println { arg, line, .. } => {
                let _ = writeln!(out, "#line {} \"{}\"", line, src);
                match arg {
                    StrArg::Local(id) => {
                        if let Some((label, len)) = labels.get(id) {
                            let _ = writeln!(out, "    fwrite({label}, 1, {len}, stdout);");
                            let _ = writeln!(out, "    fputc('\\n', stdout);");
                        }
                    }
                    StrArg::Bytes(bytes) => {
                        let label = mangle("str", counter, "");
                        counter += 1;
                        emit_array(out, &label, bytes);
                        let _ = writeln!(
                            out,
                            "    fwrite({label}, 1, {}, stdout);",
                            bytes.len()
                        );
                        let _ = writeln!(out, "    fputc('\\n', stdout);");
                    }
                }
            }
        }
    }
    out.push_str("    return 0;\n}\n");
}

fn emit_array(out: &mut String, label: &str, bytes: &[u8]) {
    let n = bytes.len();
    if n == 0 {
        // C11 无零长数组；空串用 1 字节占位，长度仍为 0。
        let _ = writeln!(out, "    static const uint8_t {label}[1] = {{0}};");
        return;
    }
    let hex: Vec<String> = bytes.iter().map(|b| format!("0x{:02x}", b)).collect();
    if hex.len() <= 16 {
        let _ = writeln!(
            out,
            "    static const uint8_t {label}[{n}] = {{{}}};",
            hex.join(", ")
        );
    } else {
        let _ = writeln!(out, "    static const uint8_t {label}[{n}] = {{");
        for chunk in hex.chunks(12) {
            let _ = writeln!(out, "        {},", chunk.join(", "));
        }
        let _ = writeln!(out, "    }};");
    }
}

#[cfg(test)]
mod tests {
    use super::{emit, escape_line_filename, mangle};
    use crate::backend::lower;
    use crate::compile_typed;

    fn ir(src: &str) -> crate::backend::ir::Program {
        let c = compile_typed(src);
        assert!(c.diags.is_empty(), "{:?}", c.diags);
        lower::lower(&c.prog, &c.types).expect("lower")
    }

    #[test]
    fn hello_emits_byte_array_and_fwrite() {
        let p = ir("fn main() {\n    let greeting = \"Hello, ZOR\";\n    println(greeting);\n}\n");
        let c = emit(&p, "examples/hello.zor");
        assert!(c.contains("#line 1 \"examples/hello.zor\""), "{c}");
        assert!(c.contains("#line 2 \"examples/hello.zor\""), "{c}");
        assert!(c.contains("#line 3 \"examples/hello.zor\""), "{c}");
        assert!(c.contains("static const uint8_t zor_str_0[10] = {0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x2c, 0x20, 0x5a, 0x4f, 0x52};"), "{c}");
        assert!(c.contains("fwrite(zor_str_0, 1, 10, stdout);"), "{c}");
        assert!(c.contains("fputc('\\n', stdout);"), "{c}");
        assert!(c.contains("int main(void) {"), "{c}");
        assert!(c.contains("return 0;"), "{c}");
    }

    #[test]
    fn empty_string_uses_one_byte_placeholder() {
        let p = ir("fn main() { let s = \"\"; println(s); }");
        let c = emit(&p, "t.zor");
        assert!(c.contains("static const uint8_t zor_str_0[1] = {0};"), "{c}");
        assert!(c.contains("fwrite(zor_str_0, 1, 0, stdout);"), "{c}");
    }

    #[test]
    fn utf8_bytes_are_emitted_verbatim() {
        let p = ir("fn main() { let s = \"你好\"; println(s); }");
        let c = emit(&p, "t.zor");
        assert!(
            c.contains("zor_str_0[6] = {0xe4, 0xbd, 0xa0, 0xe5, 0xa5, 0xbd}"),
            "{c}"
        );
        assert!(c.contains("fwrite(zor_str_0, 1, 6, stdout);"), "{c}");
    }

    #[test]
    fn literal_println_emits_inline_array() {
        let p = ir("fn main() { println(\"hi\"); }");
        let c = emit(&p, "t.zor");
        assert!(c.contains("zor_str_0[2] = {0x68, 0x69}"), "{c}");
        assert!(c.contains("fwrite(zor_str_0, 1, 2, stdout);"), "{c}");
    }

    #[test]
    fn line_filename_is_escaped() {
        assert_eq!(escape_line_filename("a\"b\\c\nd"), "a\\\"b\\\\c\\012d");
        assert_eq!(
            escape_line_filename("你好"),
            "\\344\\275\\240\\345\\245\\275"
        );
    }

    #[test]
    fn mangle_sanitizes_identifiers() {
        assert_eq!(mangle("str", 0, ""), "zor_str_0");
        assert_eq!(mangle("fn", 3, "main"), "zor_fn_3_main");
        assert_eq!(mangle("fn", 1, "a-b c"), "zor_fn_1_a_b_c");
    }

    #[test]
    fn output_is_deterministic() {
        let p = ir("fn main() { let s = \"x\"; println(s); }");
        assert_eq!(emit(&p, "t.zor"), emit(&p, "t.zor"));
    }
}
